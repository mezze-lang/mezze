package com.mezze.interpreter.bench

import java.io.File
import java.util.concurrent.ConcurrentLinkedQueue
import kotlin.system.measureNanoTime

/**
 * Shared recorder for all perf benchmarks run under `:interpreter:bench`.
 *
 * Tests call [bench] with a label + a body. The recorder runs warmup +
 * timed runs, records min/median/max in nanoseconds, and appends the
 * result to a JVM-wide queue.
 *
 * After all benches run, [writeMarkdown] dumps the accumulated results
 * to a markdown file (default: planned_features/runtime/perf-baseline.md). The
 * bench harness uses a JUnit lifecycle hook in `BenchSummaryWriter` to
 * trigger this once at the end of the test run.
 *
 * Threading: results queue is concurrent so parallel test classes
 * (currently disallowed under @Execution(SAME_THREAD), but defensive)
 * don't race on append.
 */
object BenchRecorder {
    data class Result(
        val category: String,
        val label: String,
        val iters: Int,
        val minNs: Long,
        val medianNs: Long,
        val maxNs: Long,
    ) {
        val perIterNs: Long get() = if (iters > 0) medianNs / iters else medianNs
        val perIterMicros: Double get() = perIterNs / 1_000.0

        fun toMarkdownRow(): String = String.format(
            "| %s | %d | %,d ns | %,d ns | %,d ns | %.2f µs |",
            label, iters, minNs, medianNs, maxNs, perIterMicros,
        )
    }

    private val results = ConcurrentLinkedQueue<Result>()
    private val perCategoryResults = mutableMapOf<String, MutableList<Result>>()

    /**
     * Run [body] [iters] times (with [warmup] warmup runs first), record
     * timings under [category]/[label]. Body is called as-is; the inner
     * `iters` count is purely a label-divisor for "per-iteration cost".
     *
     * For benches that themselves loop internally (e.g., "1000 op-calls
     * inside one perform"), pass that count as [iters] so the recorder
     * can compute per-op cost in the markdown output.
     */
    fun bench(
        category: String,
        label: String,
        iters: Int = 1,
        warmup: Int = 3,
        runs: Int = 5,
        body: () -> Unit,
    ): Result {
        repeat(warmup) { body() }
        val times = LongArray(runs)
        for (i in 0 until runs) {
            times[i] = measureNanoTime { body() }
        }
        times.sort()
        val r = Result(
            category = category,
            label = label,
            iters = iters,
            minNs = times.first(),
            medianNs = times[runs / 2],
            maxNs = times.last(),
        )
        results.add(r)
        synchronized(perCategoryResults) {
            perCategoryResults.getOrPut(category) { mutableListOf() }.add(r)
        }
        System.err.println(
            "[bench] $category :: $label  min=${r.minNs / 1_000} µs  " +
                "median=${r.medianNs / 1_000} µs  per-iter=${"%.2f".format(r.perIterMicros)} µs  " +
                "(iters=$iters, runs=$runs)"
        )
        return r
    }

    /**
     * Write the accumulated results to a markdown file. Intended to be
     * called after the bench task completes (e.g., via a `@AfterAll`
     * hook on a dedicated summary class).
     */
    fun writeMarkdown(out: File, gitSha: String? = null) {
        out.parentFile?.mkdirs()
        out.printWriter().use { w ->
            w.println("# Mezze runtime performance baseline")
            w.println()
            w.println("_Generated by `:interpreter:bench`._")
            if (gitSha != null) w.println("_Git: ${gitSha}_")
            w.println()
            w.println("Numbers are end-to-end (Polyglot Context + JIT warmup + measurement).")
            w.println("Use the **per-iteration µs** column to compare designs — the wall-clock")
            w.println("column includes interpreter overhead that swamps everything < 10µs.")
            w.println()

            val grouped: Map<String, List<Result>>
            synchronized(perCategoryResults) {
                grouped = perCategoryResults.mapValues { it.value.toList() }
            }
            for ((category, results) in grouped.toSortedMap()) {
                w.println("## $category")
                w.println()
                w.println("| Benchmark | Iters | Min | Median | Max | Per-iter |")
                w.println("|---|---:|---:|---:|---:|---:|")
                for (r in results) w.println(r.toMarkdownRow())
                w.println()
            }
        }
        System.err.println("[bench] wrote ${results.size} results to $out")
    }

    /**
     * Record a single measurement directly (no warmup/runs). Useful for
     * macro benchmarks that already do their own timing structure (e.g.,
     * sequential-vs-parallel comparisons).
     */
    fun record(
        category: String,
        label: String,
        nanos: Long,
        iters: Int = 1,
    ): Result {
        val r = Result(
            category = category,
            label = label,
            iters = iters,
            minNs = nanos,
            medianNs = nanos,
            maxNs = nanos,
        )
        results.add(r)
        synchronized(perCategoryResults) {
            perCategoryResults.getOrPut(category) { mutableListOf() }.add(r)
        }
        System.err.println(
            "[bench] $category :: $label  duration=${nanos / 1_000_000} ms  " +
                "(iters=$iters, single-shot)"
        )
        return r
    }

    /** For tests / debugging. */
    fun allResults(): List<Result> = results.toList()
    fun clear() {
        results.clear()
        synchronized(perCategoryResults) { perCategoryResults.clear() }
    }
}
