package com.mezze.interpreter.codec

import com.mezze.interpreter.MezzeTestHelper
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import kotlin.test.assertEquals

/**
 * A.3 — a call site must EMIT the ability obligation its callee declares.
 *
 * `from_json`'s signature is
 *
 *     from_json: { it: Str } with Decode JsonC 'a -> Result 'a DecodeError
 *
 * and the three sites that turn a callee's written obligation into a call-site
 * constraint all read it as `typeArgs.first()`, keeping the constraint only when
 * that first argument is a type VARIABLE. `Decode 'config 'a for 'in` puts the
 * config first, so the head here is the concrete `JsonC` and the obligation was
 * dropped in full — the caller's solve never saw a `Decode` constraint at all.
 *
 * Measured before the fix: the only `Decode` constraint reaching the solver came
 * from `from_json`'s own DECLARATION, in a solve disjoint from any caller's,
 * where `'a` is universally quantified and pins nothing. The two solves shared no
 * type-variable ids.
 *
 * With the obligation emitted at the call site it carries that call's own target
 * var, which the `HasField` constraints generated by the usage already pin; the
 * existing post-substitution discharge then synthesises the codec impl per shape.
 *
 * The observable consequence is below: TWO decodes of DIFFERENT shapes in one
 * scope. Nothing but the per-call target tells their decoders apart.
 */
class DecodeConstraintAtCallSiteTest {

    @BeforeEach
    fun setUp() {
        com.mezze.language.typechecker.ModuleResolver.clearCache()
    }

    private fun run(src: String): Any = MezzeTestHelper.run(src)

    @Test
    fun `two from_json calls of different shapes in one scope decode independently`() {
        val src = """
            use std::codec::json::{ FromJson }
            use std::codec::core::{ DecodeError }
            let a: Result { name: Str } DecodeError = "{\"name\":\"Ada\"}".from_json {}
            let b: Result { n: Int } DecodeError = "{\"n\":7}".from_json {}
            let an = match a is
              Ok { val = { name } } -> name
              Err { error = _ } -> "err"
            let bn = match b is
              Ok { val = { n } } -> n
              Err { error = _ } -> 0
            an.concat { r = bn.to_str {} }
        """.trimIndent()
        assertEquals("Ada7", run(src))
    }

    @Test
    fun `the same shape decoded twice still resolves`() {
        // The one-shape case was never broken; kept so a fix that specialises on
        // "more than one target in scope" cannot pass this file while regressing
        // the ordinary path.
        val src = """
            use std::codec::json::{ FromJson }
            use std::codec::core::{ DecodeError }
            let a: Result { name: Str } DecodeError = "{\"name\":\"Ada\"}".from_json {}
            let b: Result { name: Str } DecodeError = "{\"name\":\"Lin\"}".from_json {}
            let an = match a is
              Ok { val = { name } } -> name
              Err { error = _ } -> "err"
            let bn = match b is
              Ok { val = { name } } -> name
              Err { error = _ } -> "err"
            an.concat { r = bn }
        """.trimIndent()
        assertEquals("AdaLin", run(src))
    }

    @Test
    fun `a decode target inferred purely from field usage, with no annotation`() {
        // No `let a: Result {…}` annotation anywhere: the target is pinned only by
        // the field read inside the callback. This is the case A.2 is blocked on —
        // a type annotation must never be REQUIRED to typecheck.
        val src = """
            use std::codec::json::{ FromJson }
            use std::codec::core::{ DecodeError }
            use std::result
            match "{\"n\":7}".from_json {}.map { f = { val } -> val.n } is
              Ok { val } -> val
              Err { error = _ } -> 0
        """.trimIndent()
        assertEquals(7L, run(src))
    }
}
