#!/usr/bin/env bash
# Regenerate the parser-derived corpus by REPLAYING the parser test suite.
#
# This is the automatic sync mechanism: the parser is the source of truth, and
# its ~700 tests are the spec. We run :parser:test with capture on, which
# records every source the tests parse plus whether the parser accepted it, then
# split that into two block-delimited corpus files:
#
#   fixtures/parser-corpus/generated/accepted.mz  — must PARSE (no ERROR)
#   fixtures/parser-corpus/generated/rejected.mz  — must be REJECTED (has ERROR)
#
# scripts/parity.sh checks tree-sitter against both directions. Add a language
# feature to the parser + a test, re-run this, and the grammar's obligations
# update automatically — no hand-authoring.
#
# Usage:  scripts/gen-from-parser-tests.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GRAMMAR_DIR="$(cd "$HERE/.." && pwd)"
REPO_ROOT="$(cd "$GRAMMAR_DIR/../.." && pwd)"
GEN_DIR="$REPO_ROOT/fixtures/parser-corpus/generated"
NDJSON="$REPO_ROOT/parser/build/corpus-capture.ndjson"

echo "==> Replaying :parser:test with corpus capture …"
( cd "$REPO_ROOT" && MEZZE_CORPUS_CAPTURE="$NDJSON" ./gradlew :parser:test --rerun-tasks -q )

[[ -f "$NDJSON" ]] || { echo "error: no capture file at $NDJSON" >&2; exit 1; }
mkdir -p "$GEN_DIR"

echo "==> Splitting into accepted / rejected corpora …"
node - "$NDJSON" "$GEN_DIR" <<'JS'
const fs = require('fs');
const [ndjson, outDir] = process.argv.slice(2);

const accepted = [], rejected = [];
for (const line of fs.readFileSync(ndjson, 'utf8').split('\n')) {
  if (!line.trim()) continue;
  const { accepted: ok, source } = JSON.parse(line);
  (ok ? accepted : rejected).push(source);
}
// Stable order: sort so regeneration is deterministic (diff-friendly).
accepted.sort(); rejected.sort();

function write(file, header, snippets) {
  const parts = [header, ''];
  snippets.forEach((s, i) => {
    parts.push(`# === ${i + 1}`);
    parts.push(s);
    parts.push('');
  });
  fs.writeFileSync(file, parts.join('\n'));
}

write(`${outDir}/accepted.mz`,
  `# DO NOT EDIT — generated by scripts/gen-from-parser-tests.sh from the\n` +
  `# parser test suite. Every block MUST parse under tree-sitter with no ERROR.\n` +
  `# ${accepted.length} snippets the parser accepts.`,
  accepted);

write(`${outDir}/rejected.mz`,
  `# DO NOT EDIT — generated by scripts/gen-from-parser-tests.sh from the\n` +
  `# parser test suite. Every block MUST be REJECTED by tree-sitter (an ERROR\n` +
  `# node must appear) — the grammar should refuse what the parser refuses.\n` +
  `# ${rejected.length} snippets the parser rejects.`,
  rejected);

console.log(`   accepted: ${accepted.length} -> ${outDir}/accepted.mz`);
console.log(`   rejected: ${rejected.length} -> ${outDir}/rejected.mz`);
JS

echo "==> Done. Run scripts/parity.sh to check tree-sitter against both."
