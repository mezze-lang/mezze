#!/usr/bin/env bash
# Generate the tree-sitter corpus (`test/corpus/from-fixtures.txt`) from the
# shared parser fixtures. Each fixture block becomes one corpus test whose
# expected s-expression is the CURRENT parse tree — a golden snapshot.
#
# The shared parity script (parity.sh) is the *semantic* gate: every fixture
# must parse with no ERROR. This generator turns those same fixtures into a
# *structural* regression guard: `tree-sitter test` fails if a grammar edit
# changes a tree shape, so intentional shape changes are reviewed as a diff.
#
# Workflow: edit grammar.js -> `scripts/gen-corpus.sh` -> review the corpus
# diff -> commit. Never hand-edit the generated file (it has a DO-NOT-EDIT
# banner).
#
# Writes ONE corpus file (not one per snippet) to keep `tree-sitter test` fast.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GRAMMAR_DIR="$(cd "$HERE/.." && pwd)"
REPO_ROOT="$(cd "$GRAMMAR_DIR/../.." && pwd)"
FIXTURE_DIR="$REPO_ROOT/fixtures/parser-corpus"
OUT="$GRAMMAR_DIR/test/corpus/from-fixtures.txt"

( cd "$GRAMMAR_DIR" && tree-sitter generate >/dev/null )

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

{
  echo "# DO NOT EDIT — generated by scripts/gen-corpus.sh from"
  echo "# fixtures/parser-corpus/*.mz. Regenerate after grammar changes and"
  echo "# review the diff. The parity script (scripts/parity.sh) is the"
  echo "# authoritative 'must parse' gate; this file guards tree SHAPE."
  echo
} > "$OUT"

for fixture in "$FIXTURE_DIR"/*.mz; do
  [[ -e "$fixture" ]] || continue
  fname="$(basename "$fixture" .mz)"
  awk -v out="$tmp" -v base="$fname" '
    /^# ===/ { blk++; label=$0; sub(/^# === ?/, "", label); labels[blk]=label
               print label > (out "/" base "." blk ".label"); next }
    { if (blk>0) print >> (out "/" base "." blk ".mz") }
  ' "$fixture"

  for blk in "$tmp/$fname".*.mz; do
    [[ -e "$blk" ]] || continue
    grep -qvE '^\s*(#.*)?$' "$blk" || continue
    n="$(basename "$blk" .mz | sed "s/^$fname\.//")"
    label="$(cat "$tmp/$fname.$n.label" 2>/dev/null || echo "block $n")"
    tree="$(cd "$GRAMMAR_DIR" && tree-sitter parse "$blk" 2>/dev/null | sed -E 's/ \[[0-9]+, [0-9]+\] - \[[0-9]+, [0-9]+\]//g')"
    {
      echo "=================="
      echo "$fname: $label"
      echo "=================="
      echo
      # Strip a single trailing newline the fixture split may add.
      sed -e '$a\' "$blk" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
      echo
      echo "---"
      echo
      echo "$tree"
      echo
    } >> "$OUT"
  done
done

echo "wrote $OUT"
