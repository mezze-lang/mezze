package com.funk.language.typechecker.constraints

import com.funk.language.ast.*
import com.funk.language.typechecker.abilities.BuiltInAbilities
import com.funk.language.typechecker.context.TypingContext
import com.funk.language.typechecker.TypeCheckError
import com.funk.language.typechecker.ErrorType

/**
 * Expression constraint generator - generates constraints for all expression types.
 *
 * This is the heart of constraint-based type inference.
 * For each expression type, we:
 * 1. Generate constraints for sub-expressions
 * 2. Create fresh type variables as needed
 * 3. Add equality/ability/effect constraints
 * 4. Return ConstraintResult with type + constraints
 *
 * Design:
 * - Pure functions (no mutation!)
 * - Exhaustive when on Expression sealed interface
 * - No catch-all else clauses
 */
class ExpressionConstraintGenerator {

    /**
     * Generate constraints for an expression.
     *
     * This is the main entry point - exhaustive when on all Expression types.
     */
    fun generate(expr: Expression, context: ConstraintContext): ConstraintResult {
        return when (expr) {
            // Literals - simple types, no constraints
            is IntLiteral -> generateIntLiteral(expr, context)
            is NatLiteral -> generateNatLiteral(expr, context)
            is FloatLiteral -> generateFloatLiteral(expr, context)
            is BooleanLiteral -> generateBooleanLiteral(expr, context)
            is FractionLiteral -> generateFractionLiteral(expr, context)
            is StringLiteral -> generateStringLiteral(expr, context)
            is ArrayLiteral -> generateArrayLiteral(expr, context)

            // Variables - lookup in context
            is Identifier -> generateIdentifier(expr, context)
            is PlaceholderExpression -> generatePlaceholder(expr, context)

            // Arrays
            is ArrayAccess -> generateArrayAccess(expr, context)

            // Records
            is RecordLiteral -> generateRecordLiteral(expr, context)
            is MemberAccess -> generateMemberAccess(expr, context)
            is RecordUpdate -> generateRecordUpdate(expr, context)
            is RecordUpdateExpression -> generateRecordUpdateExpression(expr, context)

            // Variants
            is VariantConstruction -> generateVariantConstruction(expr, context)

            // Functions
            is LambdaExpression -> generateLambda(expr, context)
            is FunctionCall -> generateFunctionCall(expr, context)

            // Control flow
            is IfExpression -> generateIf(expr, context)
            is MatchExpression -> generateMatch(expr, context)

            // Blocks
            is DoExpression -> generateDo(expr, context)

            // Effects
            is PerformExpression -> generatePerform(expr, context)
            is EffectCallExpression -> generateEffectCall(expr, context)

            // State machines (generated by compiler, not user code)
            is StateMachineExpression -> generateStateMachine(expr, context)
        }
    }

    // ========================================================================
    // LITERALS
    // ========================================================================

    private fun generateIntLiteral(expr: IntLiteral, context: ConstraintContext): ConstraintResult {
        // Int literal has type Int, no constraints
        return ConstraintResult.simple(FunkType.IntType)
    }

    private fun generateNatLiteral(expr: NatLiteral, context: ConstraintContext): ConstraintResult {
        // Nat literal has type Nat, no constraints
        return ConstraintResult.simple(FunkType.NatType)
    }

    private fun generateFloatLiteral(expr: FloatLiteral, context: ConstraintContext): ConstraintResult {
        // Float literal has type Float, no constraints
        return ConstraintResult.simple(FunkType.FloatType)
    }

    private fun generateBooleanLiteral(expr: BooleanLiteral, context: ConstraintContext): ConstraintResult {
        // Boolean literal has type Bool (which is now a variant type: | True, False |)
        // BooleanLiteral(true) and BooleanLiteral(false) are treated as the Bool variant type
        val boolVariantType = FunkType.VariantType(
            constructors = mapOf(
                "True" to null,
                "False" to null
            ),
            rowVar = null
        )
        return ConstraintResult.simple(boolVariantType)
    }

    private fun generateFractionLiteral(expr: FractionLiteral, context: ConstraintContext): ConstraintResult {
        // Fraction literal has type Frac, no constraints
        return ConstraintResult.simple(FunkType.FracType)
    }

    private fun generateStringLiteral(expr: StringLiteral, context: ConstraintContext): ConstraintResult {
        if (!expr.isInterpolated) {
            // Simple string has type String, no constraints
            return ConstraintResult.simple(FunkType.StringType)
        }

        // Interpolated string: each ExpressionPart must have type String
        val constraints = mutableListOf<Constraint>()
        val undefinedVars = mutableListOf<ConstraintResult.UndefinedVariable>()

        for (part in expr.parts!!) {
            when (part) {
                is StringPart -> {
                    // String parts are fine, no constraints
                }
                is ExpressionPart -> {
                    // Expression must have type String
                    val exprResult = generate(part.expression, context)
                    constraints.addAll(exprResult.constraints)
                    undefinedVars.addAll(exprResult.undefinedVariables)
                    constraints.add(
                        Constraint.Equality(
                            left = exprResult.type,
                            right = FunkType.StringType,
                            context = "String interpolation requires String type"
                        )
                    )
                }
            }
        }

        return ConstraintResult(
            type = FunkType.StringType,
            constraints = constraints,
            undefinedVariables = undefinedVars
        )
    }

    private fun generateArrayLiteral(expr: ArrayLiteral, context: ConstraintContext): ConstraintResult {
        if (expr.elements.isEmpty()) {
            // Empty array: [element] where element is fresh type variable
            val elementType = FunkType.VarType(TypeVar.fresh())
            return ConstraintResult.simple(FunkType.ArrayType(elementType))
        }

        // Non-empty array: all elements must have same type
        val elementResults = expr.elements.map { generate(it, context) }
        val firstElementType = elementResults[0].type

        val constraints = mutableListOf<Constraint>()
        val undefinedVars = mutableListOf<ConstraintResult.UndefinedVariable>()

        // Add constraints and undefined variables from all elements
        elementResults.forEach {
            constraints.addAll(it.constraints)
            undefinedVars.addAll(it.undefinedVariables)
        }

        // All elements must have same type as first element
        for (i in 1 until elementResults.size) {
            constraints.add(
                Constraint.Equality(
                    left = elementResults[i].type,
                    right = firstElementType,
                    context = "Array elements must have same type"
                )
            )
        }

        return ConstraintResult(
            type = FunkType.ArrayType(firstElementType),
            constraints = constraints,
            undefinedVariables = undefinedVars
        )
    }

    // ========================================================================
    // VARIABLES
    // ========================================================================

    private fun generateIdentifier(expr: Identifier, context: ConstraintContext): ConstraintResult {
        // DEBUG
        if (expr.name == "Show" && System.getProperty("funk.debug.abilities") == "true") {
            println("[DEBUG ExpressionConstraints.generateIdentifier] Looking up '${expr.name}'")
        }

        // Look up variable in typing context
        return when (val result = context.typingContext.lookup(expr.name)) {
            is TypingContext.LookupResult.Found -> {
                // DEBUG
                if (expr.name == "Show" && System.getProperty("funk.debug.abilities") == "true") {
                    println("[DEBUG ExpressionConstraints.generateIdentifier] Found '${expr.name}' in context!")
                }
                when (val binding = result.binding) {
                    is TypingContext.Binding.Monomorphic -> {
                        // Monomorphic variable - use type directly
                        ConstraintResult.simple(binding.type)
                    }
                    is TypingContext.Binding.Polymorphic -> {
                        // Polymorphic variable - instantiate with fresh type variables
                        val instantiation = binding.scheme.instantiate()

                        // Convert AST AbilityConstraints to typechecker Constraint.AbilityRequired
                        val abilityConstraints = instantiation.freshConstraints.map { astConstraint ->
                            Constraint.AbilityRequired(
                                typeVar = TypeVar(astConstraint.typeParam),
                                abilityName = astConstraint.abilityName,
                                typeArgs = emptyList(),
                                context = null
                            )
                        }

                        ConstraintResult(
                            type = instantiation.type,
                            constraints = emptyList(),
                            abilityConstraints = abilityConstraints
                        )
                    }
                }
            }
            is TypingContext.LookupResult.NotFound -> {
                // Variable not found
                // (True and False should be found in context now, as they are registered as Bool variant constructors)

                // CRITICAL: Check if this is an ability or effect being used as a value
                // Abilities and effects start with uppercase but should NOT be treated as variant constructors
                // They should be marked as undefined variables so validation can catch them
                val isBuiltInAbility = BuiltInAbilities.isBuiltInAbility(expr.name)
                val isUserDefinedAbility = expr.name in context.abilityNames
                val isEffect = expr.name in context.effectNames

                // DEBUG
                if (expr.name == "Show" && System.getProperty("funk.debug.abilities") == "true") {
                    println("[DEBUG ExpressionConstraints] Checking '${expr.name}':")
                    println("  - isBuiltInAbility: $isBuiltInAbility")
                    println("  - isUserDefinedAbility: $isUserDefinedAbility")
                    println("  - context.abilityNames: ${context.abilityNames}")
                    println("  - isEffect: $isEffect")
                    println("  - context.effectNames: ${context.effectNames}")
                }

                if (isBuiltInAbility || isUserDefinedAbility || isEffect) {
                    // This is an ability or effect being used as a value - error!
                    // Mark as undefined variable so NewTypeChecker can provide a better error message
                    val freshType = FunkType.VarType(TypeVar.fresh())
                    return ConstraintResult(
                        type = freshType,
                        constraints = emptyList(),
                        undefinedVariables = listOf(
                            ConstraintResult.UndefinedVariable(
                                name = expr.name,
                                sourceLocation = expr.sourceLocation
                            )
                        )
                    )
                }

                // Check if it's a variant constructor (uppercase) or undefined variable (lowercase)
                if (expr.name.first().isUpperCase()) {
                    // Uppercase names are treated as variant constructors
                    // CRITICAL: Don't create a concrete variant type here!
                    // Instead, create a fresh type variable with a HasConstructor constraint.
                    // This allows the type variable to unify with existing variant type aliases.
                    val resultType = FunkType.VarType(TypeVar.fresh())
                    val constraints = listOf(
                        Constraint.HasConstructor(
                            variantType = resultType,
                            constructorName = expr.name,
                            payloadType = null,
                            context = "Variant constructor ${expr.name}"
                        )
                    )
                    ConstraintResult(
                        type = resultType,
                        constraints = constraints
                    )
                } else {
                    // Lowercase name - this is an undefined variable
                    // Track it for validation phase
                    val freshType = FunkType.VarType(TypeVar.fresh())
                    ConstraintResult(
                        type = freshType,
                        constraints = emptyList(),
                        undefinedVariables = listOf(
                            ConstraintResult.UndefinedVariable(
                                name = expr.name,
                                sourceLocation = expr.sourceLocation
                            )
                        )
                    )
                }
            }
        }
    }

    private fun generatePlaceholder(expr: PlaceholderExpression, context: ConstraintContext): ConstraintResult {
        // Placeholder for pipe operator - should be replaced during parsing
        // Create fresh type variable
        return ConstraintResult.simple(FunkType.VarType(TypeVar.fresh()))
    }

    // ========================================================================
    // ARRAYS
    // ========================================================================

    private fun generateArrayAccess(expr: ArrayAccess, context: ConstraintContext): ConstraintResult {
        // array[index]
        // array must be Array<T>, index must be Int, result is T

        val arrayResult = generate(expr.array, context)
        val indexResult = generate(expr.index, context)

        val elementType = FunkType.VarType(TypeVar.fresh())

        val constraints = mutableListOf<Constraint>()
        constraints.addAll(arrayResult.constraints)
        constraints.addAll(indexResult.constraints)

        // array must be Array<elementType>
        constraints.add(
            Constraint.Equality(
                left = arrayResult.type,
                right = FunkType.ArrayType(elementType),
                context = "Array access requires array type"
            )
        )

        // index must be Int
        constraints.add(
            Constraint.Equality(
                left = indexResult.type,
                right = FunkType.IntType,
                context = "Array index must be Int"
            )
        )

        return ConstraintResult(
            type = elementType,
            constraints = constraints,
            undefinedVariables = arrayResult.undefinedVariables + indexResult.undefinedVariables
        )
    }

    // ========================================================================
    // RECORDS
    // ========================================================================

    private fun generateRecordLiteral(expr: RecordLiteral, context: ConstraintContext): ConstraintResult {
        // {field1 = expr1, field2 = expr2, ...}

        val fields = mutableMapOf<String, FunkType>()
        val constraints = mutableListOf<Constraint>()
        val undefinedVars = mutableListOf<ConstraintResult.UndefinedVariable>()

        // Collect all present field names for validation
        val presentFields = expr.entries.filterIsInstance<RecordFieldEntry>().map { it.name }.toSet()

        for (entry in expr.entries) {
            when (entry) {
                is RecordFieldEntry -> {
                    val fieldValue = entry.value ?: Identifier(entry.name)
                    val fieldResult = generate(fieldValue, context)

                    fields[entry.name] = fieldResult.type
                    constraints.addAll(fieldResult.constraints)
                    undefinedVars.addAll(fieldResult.undefinedVariables)
                }
                is RecordSpreadEntry -> {
                    // Spread: {...baseRecord}
                    // TODO: Handle record spreading with row polymorphism
                    val spreadResult = generate(entry.expression, context)
                    constraints.addAll(spreadResult.constraints)
                    undefinedVars.addAll(spreadResult.undefinedVariables)
                }
            }
        }

        // VALIDATION: If expected type is present AND is a type alias, validate closed record constraints
        // This handles type annotations like: let x: ClosedPerson = { ... }
        // where ClosedPerson is a type alias for a closed record
        // IMPORTANT: Only validate TypeApplications (user-defined type aliases), NOT plain RecordTypes
        // (plain RecordTypes come from nested records and should be validated by constraint solving instead)
        val expectedType = context.expectedType
        if (expectedType != null && expectedType is FunkType.TypeApplication) {
            // Look up type declaration and resolve to RecordType
            val typeDecl = context.typeDeclarations[expectedType.constructor]
            if (typeDecl != null && typeDecl.definition is RecordDefinition) {
                val recordDef = typeDecl.definition as RecordDefinition
                // Convert RecordDefinition to RecordType (for validation purposes only)
                val fields = recordDef.fields.associate { field ->
                    field.name to convertFieldType(field.type)
                }
                val resolvedType = FunkType.RecordType(
                    fields = fields,
                    rowVar = if (recordDef.isOpen) RowVar("rest") else null
                )

                // If resolved type is a closed record, validate fields
                if (resolvedType.rowVar == null) {
                // Expected type is a closed record - validate fields match exactly
                val missingFields = resolvedType.fields.keys - presentFields
                if (missingFields.isNotEmpty()) {
                    throw TypeCheckError(
                        message = "Record literal missing required fields from type annotation: ${missingFields.joinToString(", ")}. " +
                                "Expected: ${prettyPrintType(expectedType)}, " +
                                "Got fields: ${presentFields.joinToString(", ")}",
                        expression = expr,
                        errorType = ErrorType.MISSING_FIELD,
                        context = mapOf(
                            "missingFields" to missingFields.toList(),
                            "presentFields" to presentFields.toList()
                        )
                    )
                }

                val extraFields = presentFields - resolvedType.fields.keys
                if (extraFields.isNotEmpty()) {
                    throw TypeCheckError(
                        message = "Record literal has extra fields not in type annotation: ${extraFields.joinToString(", ")}. " +
                                "Expected: ${prettyPrintType(expectedType)}, " +
                                "Got extra fields: ${extraFields.joinToString(", ")}",
                        expression = expr,
                        errorType = ErrorType.TYPE_MISMATCH,
                        context = mapOf(
                            "extraFields" to extraFields.toList(),
                            "expectedFields" to resolvedType.fields.keys.toList()
                        )
                    )
                }
            }
            }
        }

        val restFieldValue = expr.restField
        val recordType = FunkType.RecordType(
            fields = fields,
            rowVar = if (restFieldValue != null) RowVar(restFieldValue) else null
        )

        return ConstraintResult(
            type = recordType,
            constraints = constraints,
            undefinedVariables = undefinedVars
        )
    }

    private fun generateMemberAccess(expr: MemberAccess, context: ConstraintContext): ConstraintResult {
        // receiver.member

        // Special case: Check if this is an ability method access
        // Example: Show.show, NumAdd.add, Eq.eq, etc.

        // Get receiver name (works for both Identifier and VariantConstruction)
        val receiverName = when (expr.receiver) {
            is Identifier -> (expr.receiver as Identifier).name
            is VariantConstruction -> (expr.receiver as VariantConstruction).constructor
            else -> null
        }

        if (receiverName != null) {
            // Check if this is a built-in ability
            if (BuiltInAbilities.isBuiltInAbility(receiverName)) {
                val freshTypeVar = FunkType.VarType(TypeVar.fresh())
                val methodType = BuiltInAbilities.getAbilityMethodType(
                    receiverName,
                    expr.member,
                    freshTypeVar
                )

                if (methodType != null) {
                    // Found the method - create ability constraint
                    // CRITICAL FIX: Built-in abilities need ability constraints too!
                    val abilityConstraint = Constraint.AbilityRequired(
                        typeVar = freshTypeVar.variable,
                        abilityName = receiverName,
                        typeArgs = emptyList(),
                        context = "Built-in ability method call: $receiverName.${expr.member}"
                    )

                    return ConstraintResult(
                        type = methodType,
                        constraints = emptyList(),
                        abilityConstraints = listOf(abilityConstraint)
                    )
                } else {
                    // Method not found on this ability
                    // For now, return a fresh type variable
                    return ConstraintResult.simple(FunkType.VarType(TypeVar.fresh()))
                }
            }

            // Check if this is a user-defined ability
            val abilityKey = "${receiverName}_ability"
            when (val lookup = context.typingContext.lookup(abilityKey)) {
                is TypingContext.LookupResult.Found -> {
                    // Check if this is an effect (effects are stored as _ability too)
                    // We can distinguish by checking if receiverName is in effectDeclarations
                    // For now, check if it's an ability or effect by trying both

                    // Try effect operation first (if it produces suspended type)
                    val effectResult = tryGenerateEffectOperationCall(expr, receiverName, lookup.binding, context)
                    if (effectResult != null) {
                        return effectResult
                    }

                    // Otherwise, treat as ability method call
                    return generateAbilityMethodCall(expr, receiverName, lookup.binding, context)
                }
                is TypingContext.LookupResult.NotFound -> {
                    // Not an ability or effect, continue to regular field access
                }
            }
        }

        // Normal case: receiver must be record with 'member' field
        val receiverResult = generate(expr.receiver, context)
        val fieldType = FunkType.VarType(TypeVar.fresh())

        // CRITICAL: Validate field access on record literals (matches OldTypeChecker.kt:6260-6310)
        // If receiver is an identifier bound to a RecordLiteral, check field exists immediately
        if (expr.receiver is Identifier) {
            val receiverName = (expr.receiver as Identifier).name

            // Check if this variable was bound to a record literal
            if (receiverName in context.recordLiteralBindings) {
                // This is a record literal - validate field exists in the record type
                if (receiverResult.type is FunkType.RecordType) {
                    val recordType = receiverResult.type as FunkType.RecordType

                    // Check if field exists
                    if (!recordType.fields.containsKey(expr.member)) {
                        // Field doesn't exist - check if record is closed or open
                        if (recordType.rowVar == null) {
                            // Closed record - field must exist, throw error
                            val availableFields = recordType.fields.keys.toList()
                            throw TypeCheckError(
                                message = "Field '${expr.member}' not found in record type. Available fields: ${availableFields.joinToString()}",
                                expression = expr,
                                errorType = ErrorType.MISSING_FIELD,
                                context = mapOf(
                                    "field" to expr.member,
                                    "availableFields" to availableFields
                                )
                            )
                        } else {
                            // Open record with explicit literal - still fail
                            // OldTypeChecker validates this too (line 6285-6300)
                            val availableFields = recordType.fields.keys.toList()
                            throw TypeCheckError(
                                message = "Field '${expr.member}' not found in open record. Explicitly declared fields: ${availableFields.joinToString()}",
                                expression = expr,
                                errorType = ErrorType.MISSING_FIELD,
                                context = mapOf(
                                    "field" to expr.member,
                                    "availableFields" to availableFields
                                )
                            )
                        }
                    }
                }
            }
        }

        val constraints = mutableListOf<Constraint>()
        constraints.addAll(receiverResult.constraints)

        // Add HasField constraint
        constraints.add(
            Constraint.HasField(
                recordType = receiverResult.type,
                fieldName = expr.member,
                fieldType = fieldType,
                context = "Field access ${expr.member}"
            )
        )

        return ConstraintResult(
            type = fieldType,
            constraints = constraints,
            undefinedVariables = receiverResult.undefinedVariables
        )
    }

    /**
     * Generate constraints for ability method calls.
     *
     * Example: Show.show {val = person}
     *
     * Steps:
     * 1. Get ability type (RecordType with methods as fields)
     * 2. Instantiate with fresh type variables
     * 3. Look up method
     * 4. Add ability constraint to function type
     */
    private fun generateAbilityMethodCall(
        expr: MemberAccess,
        abilityName: String,
        abilityBinding: TypingContext.Binding,
        context: ConstraintContext
    ): ConstraintResult {
        // Get ability type from binding
        val abilityType = when (abilityBinding) {
            is TypingContext.Binding.Monomorphic -> abilityBinding.type
            is TypingContext.Binding.Polymorphic -> {
                // Instantiate polymorphic ability type with fresh type variables
                abilityBinding.scheme.instantiate().type
            }
        }

        // Ability should be stored as RecordType with methods as fields
        if (abilityType !is FunkType.RecordType) {
            // Shouldn't happen if ContextBuilder is working correctly
            throw IllegalStateException("Ability '$abilityName' is not properly registered")
        }

        // Look up method in ability
        val methodName = expr.member
        val methodType = abilityType.fields[methodName]

        if (methodType == null) {
            // Method not found
            val availableMethods = abilityType.fields.keys.joinToString(", ")
            throw IllegalStateException(
                "Method '$methodName' not found in ability '$abilityName'. Available methods: $availableMethods"
            )
        }

        // Instantiate method type with fresh type variables
        // This prevents type variable pollution across different method calls
        val instantiatedMethodType = instantiateTypeWithFreshVars(methodType)

        // Add ability constraint to the function type
        if (instantiatedMethodType is FunkType.FunctionType) {
            val typeVars = extractTypeVariables(instantiatedMethodType)

            if (typeVars.isEmpty()) {
                // No type variables, no constraint needed
                return ConstraintResult.simple(instantiatedMethodType)
            }

            // Create ability constraint for the primary type variable
            // Convert type variables to type arguments (wrapped in VarType)
            val typeArgs = typeVars.drop(1).map { FunkType.VarType(it) }

            val abilityConstraint = Constraint.AbilityRequired(
                typeVar = typeVars.first(),
                abilityName = abilityName,
                typeArgs = typeArgs,  // Additional type arguments if multi-parameter ability
                context = "Ability method call: $abilityName.$methodName"
            )

            return ConstraintResult(
                type = instantiatedMethodType,
                constraints = emptyList(),
                abilityConstraints = listOf(abilityConstraint)
            )
        }

        // Non-function type (shouldn't happen for ability methods)
        return ConstraintResult.simple(instantiatedMethodType)
    }

    /**
     * Try to generate constraints for effect operation calls.
     *
     * Example: Log.println {msg = "Hello"}
     *
     * Returns null if this is not an effect operation (so caller can try ability method instead).
     * Returns ConstraintResult if this is an effect operation.
     *
     * Effect operations are similar to ability methods, but they wrap the result in SuspendedType with the effect.
     */
    private fun tryGenerateEffectOperationCall(
        expr: MemberAccess,
        effectName: String,
        effectBinding: TypingContext.Binding,
        context: ConstraintContext
    ): ConstraintResult? {
        // Check if this is actually an effect (not an ability)
        if (effectName !in context.effectNames) {
            return null  // Not an effect, caller will try ability method
        }

        // Get effect type from binding
        val effectType = when (effectBinding) {
            is TypingContext.Binding.Monomorphic -> effectBinding.type
            is TypingContext.Binding.Polymorphic -> {
                // Instantiate polymorphic effect type with fresh type variables
                effectBinding.scheme.instantiate().type
            }
        }

        // Effect should be stored as RecordType with operations as fields
        if (effectType !is FunkType.RecordType) {
            // Shouldn't happen if ContextBuilder is working correctly
            throw IllegalStateException("Effect '$effectName' is not properly registered")
        }

        // Look up operation in effect
        val operationName = expr.member
        val operationType = effectType.fields[operationName]

        if (operationType == null) {
            // Operation not found
            val availableOperations = effectType.fields.keys.joinToString(", ")
            throw IllegalStateException(
                "Operation '$operationName' not found in effect '$effectName'. Available operations: $availableOperations"
            )
        }

        // For effect operations, we DON'T want to instantiate with fresh vars yet
        // because we need to preserve associated type variable names for substitution
        // We'll instantiate AFTER substitution if needed
        var instantiatedOperationType = operationType

        // CRITICAL: If we're in a perform context and this effect has associated types,
        // substitute the associated type variables with the concrete types from the performer
        // This matches OldTypeChecker.kt lines 4810-4854
        val performContext = context.performContext
        if (performContext != null && instantiatedOperationType is FunkType.FunctionType) {
            // Find which performer is handling this effect
            // The performer handlers are in performContext.handlers
            var performerName: String? = null

            // Try each handler in the perform context
            for (handler in performContext.handlers) {
                val handlerEffectName = context.performerToEffect[handler.name]
                if (handlerEffectName == effectName) {
                    performerName = handler.name
                    break
                }
            }

            if (performerName != null) {
                // Get the performer's associated type bindings
                val performerKey = "${performerName}_performer"
                when (val lookup = context.typingContext.lookup(performerKey)) {
                    is TypingContext.LookupResult.Found -> {
                        // Performer bindings are stored as a RecordType with associated type bindings
                        val performerBinding = lookup.binding
                        val performerType = when (performerBinding) {
                            is TypingContext.Binding.Monomorphic -> performerBinding.type
                            is TypingContext.Binding.Polymorphic -> performerBinding.scheme.type
                        }

                        if (performerType is FunkType.RecordType) {
                            // Substitute associated types in the operation type
                            // The performer's type has fields like: {env -> String}
                            instantiatedOperationType = substituteAssociatedTypesInType(
                                instantiatedOperationType,
                                performerType.fields
                            )
                        }
                    }
                    is TypingContext.LookupResult.NotFound -> {
                        // Performer not registered - might happen for some tests
                    }
                }
            }
        }

        // NOW instantiate with fresh vars to avoid variable sharing across different calls
        // But this is AFTER substitution, so associated types have been replaced with concrete types
        instantiatedOperationType = instantiateTypeWithFreshVars(instantiatedOperationType)

        // Return the plain function type with the effect tracked in ConstraintResult
        // When this operation is called, the effect will be collected and propagated
        // This matches how OldTypeChecker handled effect operations
        return ConstraintResult(
            type = instantiatedOperationType,
            constraints = emptyList(),
            effects = setOf(effectName),  // Track effect here, not in function type
            undefinedVariables = emptyList()
        )
    }

    /**
     * Substitute associated type variables in a type with concrete types.
     * Used for effect operations with associated types.
     *
     * Example: If operation type is `{value: 'state} -> 'state <State>`
     *          and bindings is `{'state -> Int}`
     *          Result is `{value: Int} -> Int <State>`
     */
    private fun substituteAssociatedTypesInType(
        type: FunkType,
        associatedTypeBindings: Map<String, FunkType>
    ): FunkType {
        return when (type) {
            is FunkType.VarType -> {
                // CRITICAL: Associated type variables are represented as VarType with name like ''env'
                // The performer bindings map has keys like "env" (without ')
                // So we need to check both with and without the ' prefix
                val varName = type.variable.name
                // Try looking up with name as-is, then without ' prefix
                val keyWithoutQuote = varName.removePrefix("'")
                associatedTypeBindings[varName] ?: associatedTypeBindings[keyWithoutQuote] ?: type
            }
            is FunkType.TypeApplication -> {
                // Check if this is an associated type reference (e.g., 'state)
                if (type.args.isEmpty() && type.constructor.startsWith("'")) {
                    // This is an associated type variable - substitute it
                    associatedTypeBindings[type.constructor] ?: type
                } else {
                    // Regular type application - recurse into args
                    FunkType.TypeApplication(
                        constructor = type.constructor,
                        args = type.args.map { substituteAssociatedTypesInType(it, associatedTypeBindings) }
                    )
                }
            }
            is FunkType.FunctionType -> FunkType.FunctionType(
                paramType = substituteAssociatedTypesInType(type.paramType, associatedTypeBindings),
                returnType = substituteAssociatedTypesInType(type.returnType, associatedTypeBindings),
                effects = type.effects,
                abilityConstraints = type.abilityConstraints
            )
            is FunkType.RecordType -> FunkType.RecordType(
                fields = type.fields.mapValues { (_, fieldType) ->
                    substituteAssociatedTypesInType(fieldType, associatedTypeBindings)
                },
                rowVar = type.rowVar
            )
            is FunkType.VariantType -> FunkType.VariantType(
                constructors = type.constructors.mapValues { (_, dataType) ->
                    dataType?.let { substituteAssociatedTypesInType(it, associatedTypeBindings) }
                },
                rowVar = type.rowVar
            )
            is FunkType.ArrayType -> FunkType.ArrayType(
                elementType = substituteAssociatedTypesInType(type.elementType, associatedTypeBindings)
            )
            is FunkType.ListType -> FunkType.ListType(
                elementType = substituteAssociatedTypesInType(type.elementType, associatedTypeBindings)
            )
            is FunkType.SetType -> FunkType.SetType(
                elementType = substituteAssociatedTypesInType(type.elementType, associatedTypeBindings)
            )
            is FunkType.MapType -> FunkType.MapType(
                keyType = substituteAssociatedTypesInType(type.keyType, associatedTypeBindings),
                valueType = substituteAssociatedTypesInType(type.valueType, associatedTypeBindings)
            )
            is FunkType.SuspendedType -> FunkType.SuspendedType(
                valueType = substituteAssociatedTypesInType(type.valueType, associatedTypeBindings),
                effects = type.effects
            )
            // Primitive types and VarType unchanged
            is FunkType.VarType, is FunkType.IntType, is FunkType.FloatType, is FunkType.StringType,
            is FunkType.BooleanType, is FunkType.NatType, is FunkType.FracType,
            is FunkType.OrderingType, is FunkType.EffectRow -> type
        }
    }

    /**
     * Instantiate a type with fresh type variables.
     * Replaces all type variables with fresh ones.
     * CRITICAL: Preserves variable names for associated types (names starting with ')
     */
    private fun instantiateTypeWithFreshVars(type: FunkType): FunkType {
        val freeVars = getFreeTypeVariables(type)
        if (freeVars.isEmpty()) {
            return type
        }

        // CRITICAL: Preserve names for associated type variables (those starting with ')
        // This allows them to be matched with performer bindings later
        val substitution = freeVars.associateWith { oldVar ->
            if (oldVar.name.startsWith("'")) {
                // Associated type variable - preserve the name but create new instance
                TypeVar(oldVar.name)
            } else {
                // Regular type variable - create fresh one
                TypeVar.fresh()
            }
        }
        return applyTypeVarSubstitution(type, substitution)
    }

    /**
     * Get all free type variables in a type.
     */
    private fun getFreeTypeVariables(type: FunkType): Set<TypeVar> {
        return when (type) {
            is FunkType.VarType -> setOf(type.variable)
            is FunkType.FunctionType -> {
                getFreeTypeVariables(type.paramType) + getFreeTypeVariables(type.returnType)
            }
            is FunkType.RecordType -> {
                type.fields.values.flatMap { getFreeTypeVariables(it) }.toSet()
            }
            is FunkType.VariantType -> {
                type.constructors.values.filterNotNull().flatMap { getFreeTypeVariables(it) }.toSet()
            }
            is FunkType.ArrayType -> getFreeTypeVariables(type.elementType)
            is FunkType.ListType -> getFreeTypeVariables(type.elementType)
            is FunkType.SetType -> getFreeTypeVariables(type.elementType)
            is FunkType.MapType -> getFreeTypeVariables(type.keyType) + getFreeTypeVariables(type.valueType)
            is FunkType.SuspendedType -> getFreeTypeVariables(type.valueType)
            is FunkType.TypeApplication -> type.args.flatMap { getFreeTypeVariables(it) }.toSet()
            // Primitive types have no variables
            is FunkType.IntType, is FunkType.FloatType, is FunkType.StringType,
            is FunkType.BooleanType, is FunkType.NatType, is FunkType.FracType,
            is FunkType.OrderingType, is FunkType.EffectRow -> emptySet()
        }
    }

    /**
     * Apply type variable substitution to a type.
     */
    private fun applyTypeVarSubstitution(type: FunkType, substitution: Map<TypeVar, TypeVar>): FunkType {
        return when (type) {
            is FunkType.VarType -> {
                val newVar = substitution[type.variable]
                if (newVar != null) FunkType.VarType(newVar) else type
            }
            is FunkType.FunctionType -> FunkType.FunctionType(
                paramType = applyTypeVarSubstitution(type.paramType, substitution),
                returnType = applyTypeVarSubstitution(type.returnType, substitution),
                effects = type.effects,
                abilityConstraints = type.abilityConstraints  // Keep constraints as-is for now
            )
            is FunkType.RecordType -> FunkType.RecordType(
                fields = type.fields.mapValues { (_, fieldType) ->
                    applyTypeVarSubstitution(fieldType, substitution)
                },
                rowVar = type.rowVar
            )
            is FunkType.VariantType -> FunkType.VariantType(
                constructors = type.constructors.mapValues { (_, dataType) ->
                    dataType?.let { applyTypeVarSubstitution(it, substitution) }
                },
                rowVar = type.rowVar
            )
            is FunkType.ArrayType -> FunkType.ArrayType(
                elementType = applyTypeVarSubstitution(type.elementType, substitution)
            )
            is FunkType.ListType -> FunkType.ListType(
                elementType = applyTypeVarSubstitution(type.elementType, substitution)
            )
            is FunkType.SetType -> FunkType.SetType(
                elementType = applyTypeVarSubstitution(type.elementType, substitution)
            )
            is FunkType.MapType -> FunkType.MapType(
                keyType = applyTypeVarSubstitution(type.keyType, substitution),
                valueType = applyTypeVarSubstitution(type.valueType, substitution)
            )
            is FunkType.SuspendedType -> FunkType.SuspendedType(
                valueType = applyTypeVarSubstitution(type.valueType, substitution),
                effects = type.effects
            )
            is FunkType.TypeApplication -> FunkType.TypeApplication(
                constructor = type.constructor,
                args = type.args.map { applyTypeVarSubstitution(it, substitution) }
            )
            // Primitive types unchanged
            is FunkType.IntType, is FunkType.FloatType, is FunkType.StringType,
            is FunkType.BooleanType, is FunkType.NatType, is FunkType.FracType,
            is FunkType.OrderingType, is FunkType.EffectRow -> type
        }
    }

    /**
     * Extract type variables from a type in order.
     * Used for ability constraint generation.
     */
    private fun extractTypeVariables(type: FunkType): List<TypeVar> {
        // For function types, we want type variables from parameters first
        return when (type) {
            is FunkType.VarType -> listOf(type.variable)
            is FunkType.FunctionType -> {
                extractTypeVariables(type.paramType) + extractTypeVariables(type.returnType)
            }
            is FunkType.RecordType -> {
                type.fields.values.flatMap { extractTypeVariables(it) }
            }
            is FunkType.VariantType -> {
                type.constructors.values.filterNotNull().flatMap { extractTypeVariables(it) }
            }
            is FunkType.ArrayType -> extractTypeVariables(type.elementType)
            is FunkType.ListType -> extractTypeVariables(type.elementType)
            is FunkType.SetType -> extractTypeVariables(type.elementType)
            is FunkType.MapType -> extractTypeVariables(type.keyType) + extractTypeVariables(type.valueType)
            is FunkType.SuspendedType -> extractTypeVariables(type.valueType)
            is FunkType.TypeApplication -> type.args.flatMap { extractTypeVariables(it) }
            // Primitive types have no variables
            else -> emptyList()
        }
    }

    /**
     * Find an ability implementation that matches the given type arguments.
     *
     * This implements bidirectional matching from OldTypeChecker.kt lines 16246-16300:
     * - Type variables in `typeArgs` can match concrete types in implementation
     * - This enables inference: Convert Int 'a can match impl Convert Int String
     *
     * @param abilityName The ability name (e.g., "Convert")
     * @param typeArgs The type arguments from the constraint (may contain type variables)
     * @param context The constraint context (for looking up implementations)
     * @return The matched implementation's type list, or null if no match
     */
    private fun findAbilityImplementation(
        abilityName: String,
        typeArgs: List<FunkType>,
        context: ConstraintContext
    ): List<String>? {
        // Get all implementations for this ability
        val impls = context.typingContext.getAbilityImpls(abilityName)

        if (impls.isEmpty()) {
            return null
        }

        // Find implementation that matches the type arguments
        // BIDIRECTIONAL TYPE INFERENCE: Allow type variables in constraint to match concrete types in implementation
        for (impl in impls) {
            if (impl.targetTypes.size != typeArgs.size) {
                continue
            }

            // Check if all target types match (allowing type variables to unify)
            var allMatch = true
            for (i in typeArgs.indices) {
                val implTypeName = impl.targetTypes[i]  // Type name from implementation (e.g., "String")
                val constraintType = typeArgs[i]  // Type from constraint (may have type variables)

                // Bidirectional matching: Allow constraint type variables to match impl concrete types
                val canMatch = when (constraintType) {
                    is FunkType.VarType -> {
                        // Type variable can match any concrete type
                        // This enables inference: Convert Int 'a can match impl Convert Int String
                        true
                    }
                    is FunkType.IntType -> implTypeName == "Int"
                    is FunkType.FloatType -> implTypeName == "Float"
                    is FunkType.StringType -> implTypeName == "String"
                    is FunkType.BooleanType -> implTypeName == "Bool"
                    is FunkType.NatType -> implTypeName == "Nat"
                    is FunkType.FracType -> implTypeName == "Frac"
                    is FunkType.OrderingType -> implTypeName == "Ordering"
                    is FunkType.TypeApplication -> {
                        // For type constructors, match by name
                        // TODO: Handle type arguments
                        implTypeName == constraintType.constructor
                    }
                    else -> {
                        // Other types - try string matching
                        implTypeName == constraintType.toString()
                    }
                }

                if (!canMatch) {
                    allMatch = false
                    break
                }
            }

            if (allMatch) {
                return impl.targetTypes
            }
        }

        return null
    }

    private fun generateRecordUpdate(expr: RecordUpdate, context: ConstraintContext): ConstraintResult {
        // {base | field1 = expr1, field2 = expr2}

        val baseResult = generate(expr.record, context)
        val constraints = mutableListOf<Constraint>()
        val undefinedVars = mutableListOf<ConstraintResult.UndefinedVariable>()

        constraints.addAll(baseResult.constraints)
        undefinedVars.addAll(baseResult.undefinedVariables)

        for (update in expr.updates) {
            val updateResult = generate(update.value ?: Identifier(update.name), context)
            constraints.addAll(updateResult.constraints)
            undefinedVars.addAll(updateResult.undefinedVariables)

            // Base record must have this field with compatible type
            constraints.add(
                Constraint.HasField(
                    recordType = baseResult.type,
                    fieldName = update.name,
                    fieldType = updateResult.type,
                    context = "Record update field ${update.name}"
                )
            )
        }

        // Result type is same as base type
        return ConstraintResult(
            type = baseResult.type,
            constraints = constraints,
            undefinedVariables = undefinedVars
        )
    }

    private fun generateRecordUpdateExpression(expr: RecordUpdateExpression, context: ConstraintContext): ConstraintResult {
        // Similar to RecordUpdate but with nested field paths
        // TODO: Implement nested field update constraints
        val baseResult = generate(expr.baseRecord, context)
        return ConstraintResult(
            type = baseResult.type,
            constraints = baseResult.constraints,
            undefinedVariables = baseResult.undefinedVariables
        )
    }

