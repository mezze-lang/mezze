    private fun generatePerform(expr: PerformExpression, context: ConstraintContext): ConstraintResult {
        // perform Handler in expr
        // The handler handles a specific effect, removing it from the expression's type

        // CRITICAL: Pass the perform context to child expressions
        // This allows effect operations to substitute associated types from the performer
        // Matches OldTypeChecker.kt lines 7353-7354
        val contextWithPerform = context.copy(performContext = expr)
        val exprResult = generate(expr.expression, contextWithPerform)

        // Map each handler name to the effect it handles
        val handledEffects = expr.handlers.mapNotNull { handler ->
            context.performerToEffect[handler.name]
        }.toSet()

        // DEBUG
        if (System.getProperty("funk.debug.effects") == "true") {
            println("[DEBUG generatePerform] Processing perform expression")
            println("  handlers: ${expr.handlers.map { it.name }}")
            println("  performerToEffect map: ${context.performerToEffect}")
            println("  handledEffects: $handledEffects")
            println("  exprResult.type: ${exprResult.type}")
        }

        // Remove handled effects from the expression's type
        val resultType = removeEffectsFromType(exprResult.type, handledEffects)

        // DEBUG
        if (System.getProperty("funk.debug.effects") == "true") {
            println("  resultType after removal: $resultType")
        }

        return ConstraintResult(
            type = resultType,
            constraints = exprResult.constraints,
            undefinedVariables = exprResult.undefinedVariables
        )
    }

    /**
     * Remove specific effects from a type.
     *
     * For FunctionType with effects: Remove effects from effect row
     * For SuspendedType with effects: Remove effects from effect row, returning pure value if all removed
     */
    private fun removeEffectsFromType(type: FunkType, effectsToRemove: Set<String>): FunkType {
        return when (type) {
            is FunkType.FunctionType -> {
                val effects = type.effects
                if (effects == null) {
                    // No effects to remove
                    type
                } else {
                    // Remove the handled effects
                    val remainingEffects = effects.effects - effectsToRemove

                    if (remainingEffects.isEmpty()) {
                        // All effects handled - return pure function
                        FunkType.FunctionType(
                            paramType = type.paramType,
                            returnType = type.returnType,
                            effects = null,  // Pure function
                            abilityConstraints = type.abilityConstraints
                        )
                    } else {
                        // Some effects remain
                        FunkType.FunctionType(
                            paramType = type.paramType,
                            returnType = type.returnType,
                            effects = FunkType.EffectRow(remainingEffects),
                            abilityConstraints = type.abilityConstraints
                        )
                    }
                }
            }
            is FunkType.SuspendedType -> {
                // Remove effects from suspended type
                val remainingEffects = type.effects.effects - effectsToRemove

                if (remainingEffects.isEmpty()) {
                    // All effects handled - return pure value
                    type.valueType
                } else {
                    // Some effects remain - still suspended
                    FunkType.SuspendedType(
                        valueType = type.valueType,
                        effects = FunkType.EffectRow(remainingEffects)
                    )
                }
            }
            else -> {
                // Other types don't have effects
                type
            }
        }
    }

