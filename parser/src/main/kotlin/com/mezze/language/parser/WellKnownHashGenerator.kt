package com.mezze.language.parser

import com.mezze.language.parsedast.*
import java.io.File

/**
 * Build-time generator: parses stdlib .mz files and outputs a Kotlin file
 * with const val hashes for all well-known abilities and effects.
 *
 * Run by Gradle during typechecker build. Output is compiled into the typechecker module.
 */
fun main(args: Array<String>) {
    val outputPath = args[0]
    val stdlibDir = File(args[1])

    val parser = com.mezze.language.parser.MezzeParser()

    // Collect all ability and effect declarations from stdlib
    val abilities = mutableMapOf<String, String>() // name → content hash
    val effects = mutableMapOf<String, String>()

    fun scanFile(file: File) {
        try {
            val source = file.readText()
            val module = parser.parseParsedModule(source, file.absolutePath)
            for (decl in module.decls) {
                when (decl) {
                    is ParsedAbilityDecl -> {
                        val hash = decl.contentHash ?: ParsedDeclHasher.hashAbilityDecl(decl)
                        abilities[decl.name] = hash
                    }
                    is ParsedEffectDecl -> {
                        val hash = decl.contentHash ?: ParsedDeclHasher.hashEffectDecl(decl)
                        effects[decl.name] = hash
                    }
                    else -> {}
                }
            }
        } catch (_: Exception) {
            // Skip files that fail to parse
        }
    }

    // Scan all .mz files in stdlib
    fun scanDir(dir: File) {
        dir.listFiles()?.forEach { file ->
            if (file.isDirectory) scanDir(file)
            else if (file.extension == "mz") scanFile(file)
        }
    }

    scanDir(stdlibDir.resolve("std"))

    // Generate Kotlin source
    val output = File(outputPath)
    output.parentFile.mkdirs()

    val sb = StringBuilder()
    sb.appendLine("package com.mezze.language.typechecker")
    sb.appendLine()
    sb.appendLine("/**")
    sb.appendLine(" * Build-time computed content hashes for all stdlib abilities and effects.")
    sb.appendLine(" * Generated by WellKnownHashGenerator — do not edit manually.")
    sb.appendLine(" */")
    sb.appendLine("object WellKnownHashConstants {")
    sb.appendLine()
    sb.appendLine("    // Ability hashes")
    for ((name, hash) in abilities.toSortedMap()) {
        sb.appendLine("    const val ABILITY_${name.uppercase()} = \"$hash\"")
    }
    sb.appendLine()
    sb.appendLine("    // Effect hashes")
    for ((name, hash) in effects.toSortedMap()) {
        sb.appendLine("    const val EFFECT_${name.uppercase()} = \"$hash\"")
    }
    sb.appendLine()
    sb.appendLine("    // Lookup tables")
    sb.appendLine("    val abilityHashes: Map<String, String> = mapOf(")
    for ((name, hash) in abilities.toSortedMap()) {
        sb.appendLine("        \"$name\" to ABILITY_${name.uppercase()},")
    }
    sb.appendLine("    )")
    sb.appendLine()
    sb.appendLine("    val effectHashes: Map<String, String> = mapOf(")
    for ((name, hash) in effects.toSortedMap()) {
        sb.appendLine("        \"$name\" to EFFECT_${name.uppercase()},")
    }
    sb.appendLine("    )")
    sb.appendLine()
    sb.appendLine("    fun resolveAbilityHash(name: String): String? = abilityHashes[name]")
    sb.appendLine("    fun resolveEffectHash(name: String): String? = effectHashes[name]")
    sb.appendLine("    fun resolveHash(name: String): String? = abilityHashes[name] ?: effectHashes[name]")
    sb.appendLine()
    sb.appendLine("    fun isInspect(hash: String?): Boolean = hash != null && hash == ABILITY_INSPECT")
    sb.appendLine("    fun isMut(hash: String?): Boolean = hash != null && hash == EFFECT_MUT")
    sb.appendLine("    fun isCodecAbility(hash: String?): Boolean = hash != null && hash in codecAbilitySet")
    sb.appendLine("    fun isEq(hash: String?): Boolean = hash != null && hash == ABILITY_EQ")
    sb.appendLine("    fun isOrd(hash: String?): Boolean = hash != null && hash == ABILITY_ORD")
    sb.appendLine("    fun isNumAdd(hash: String?): Boolean = hash != null && hash == ABILITY_NUMADD")
    sb.appendLine("    fun isNumSub(hash: String?): Boolean = hash != null && hash == ABILITY_NUMSUB")
    sb.appendLine("    fun isNumMul(hash: String?): Boolean = hash != null && hash == ABILITY_NUMMUL")
    sb.appendLine("    fun isNumDiv(hash: String?): Boolean = hash != null && hash == ABILITY_NUMDIV")
    sb.appendLine("    fun isNumMod(hash: String?): Boolean = hash != null && hash == ABILITY_NUMMOD")
    sb.appendLine()

    // Codec abilities set
    val codecNames = listOf("Encode", "EncodeRepr", "Decode", "DecodeRepr",
        "StreamEncode", "StreamDecode", "EncodeFormat", "DecodeFormat",
        "StreamFormat", "StreamDecodeFormat", "Format")
    sb.appendLine("    private val codecAbilitySet = setOf(")
    for (name in codecNames) {
        if (abilities.containsKey(name)) {
            sb.appendLine("        ABILITY_${name.uppercase()},")
        }
    }
    sb.appendLine("    )")

    sb.appendLine("}")

    output.writeText(sb.toString())
    println("Generated ${abilities.size} ability hashes + ${effects.size} effect hashes → $outputPath")
}
