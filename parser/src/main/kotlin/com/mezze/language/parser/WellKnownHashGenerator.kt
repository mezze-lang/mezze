package com.mezze.language.parser

import com.mezze.language.parsedast.*
import com.mezze.language.typedast.Hash
import java.io.File

/**
 * Build-time generator: parses stdlib .mz files and outputs a Kotlin file
 * with const val hashes for all well-known abilities and effects.
 *
 * Run by Gradle during typechecker build. Output is compiled into the typechecker module.
 */
fun main(args: Array<String>) {
    val outputPath = args[0]
    val stdlibDir = File(args[1])

    val parser = com.mezze.language.parser.MezzeParser()

    // (typed Hash end-to-end).
    val abilities = mutableMapOf<String, Hash>() // name → content hash
    val effects = mutableMapOf<String, Hash>()
    val types = mutableMapOf<String, Hash>()     // user-defined types in stdlib

    fun scanFile(file: File) {
        try {
            val source = file.readText()
            val module = parser.parseParsedModule(source, file.absolutePath)
            for (decl in module.decls) {
                when (decl) {
                    is ParsedAbilityDecl -> {
                        abilities[decl.name] = decl.contentHash ?: ParsedDeclHasher.hashAbilityDecl(decl)
                    }
                    is ParsedEffectDecl -> {
                        effects[decl.name] = decl.contentHash ?: ParsedDeclHasher.hashEffectDecl(decl)
                    }
                    is ParsedTypeDecl -> {
                        // Public types only — private types aren't well-known.
                        // a name collision across stdlib files would silently
                        // hide the second; ok for now since stdlib enforces
                        // unique names, but worth a follow-up assertion.)
                        if (decl.visibility == com.mezze.language.parsedast.Visibility.PUBLIC &&
                            !types.containsKey(decl.name)) {
                            types[decl.name] = decl.contentHash ?: ParsedDeclHasher.hashTypeDecl(decl)
                        }
                    }
                    else -> {}
                }
            }
        } catch (_: Exception) {
        }
    }

    // Scan all .mz files in stdlib
    fun scanDir(dir: File) {
        dir.listFiles()?.forEach { file ->
            if (file.isDirectory) scanDir(file)
            else if (file.extension == "mz") scanFile(file)
        }
    }

    scanDir(stdlibDir.resolve("std"))

    // Generate Kotlin source
    val output = File(outputPath)
    output.parentFile.mkdirs()

    val sb = StringBuilder()
    sb.appendLine("package com.mezze.language.typechecker")
    sb.appendLine()
    sb.appendLine("import com.mezze.language.typedast.Hash")
    sb.appendLine()
    sb.appendLine("/**")
    sb.appendLine(" * Build-time computed content hashes for all stdlib abilities and effects.")
    sb.appendLine(" * Generated by WellKnownHashGenerator — do not edit manually.")
    sb.appendLine(" */")
    // Named ABILITY_* / EFFECT_* constants are emitted ONLY for the ones actually
    // referenced by name — the is<Ability>/codec-set semantic anchors and the few
    // direct external refs. Every stdlib decl's hash still flows through the
    // abilityHashes/effectHashes/typeHashes maps below (built with inline literals),
    // which the resolve*() lookups use; the maps just don't need a named const each.
    // This drops ~90 dead named constants (all TYPE_*, most ABILITY_*/EFFECT_*). #289
    val keptAbilities = setOf(
        // is<Ability> anchors
        "Eq", "Ord", "Inspect", "NumAdd", "NumSub", "NumMul", "NumDiv", "NumMod",
        // codec-set members (codecAbilitySet / encode|decode-flavored)
        "Encode", "EncodeRepr", "Decode", "DecodeRepr",
        "StreamEncode", "StreamDecode", "DecodeFormat",
        "StreamFormat", "StreamDecodeFormat", "Format",
        // referenced directly by external code
        "LogicalAnd", "LogicalOr",
    )
    val keptEffects = setOf("Mut")

    sb.appendLine("object WellKnownHashConstants {")
    sb.appendLine()
    sb.appendLine("    // Semantic-anchor ability hashes (referenced by name below)")
    for ((name, hash) in abilities.toSortedMap()) {
        if (name in keptAbilities) sb.appendLine("    val ABILITY_${name.uppercase()} = Hash(\"${hash.hex}\")")
    }
    sb.appendLine()
    sb.appendLine("    // Semantic-anchor effect hashes (referenced by name below)")
    for ((name, hash) in effects.toSortedMap()) {
        if (name in keptEffects) sb.appendLine("    val EFFECT_${name.uppercase()} = Hash(\"${hash.hex}\")")
    }
    sb.appendLine()
    sb.appendLine("    // Lookup tables — name → content hash for stdlib abilities/effects/types.")
    sb.appendLine("    // Values are inline literals except where a named anchor const exists above.")
    sb.appendLine("    val abilityHashes: Map<String, Hash> = mapOf(")
    for ((name, hash) in abilities.toSortedMap()) {
        val rhs = if (name in keptAbilities) "ABILITY_${name.uppercase()}" else "Hash(\"${hash.hex}\")"
        sb.appendLine("        \"$name\" to $rhs,")
    }
    sb.appendLine("    )")
    sb.appendLine()
    sb.appendLine("    val effectHashes: Map<String, Hash> = mapOf(")
    for ((name, hash) in effects.toSortedMap()) {
        val rhs = if (name in keptEffects) "EFFECT_${name.uppercase()}" else "Hash(\"${hash.hex}\")"
        sb.appendLine("        \"$name\" to $rhs,")
    }
    sb.appendLine("    )")
    sb.appendLine()
    sb.appendLine("    val typeHashes: Map<String, Hash> = mapOf(")
    for ((name, hash) in types.toSortedMap()) {
        sb.appendLine("        \"$name\" to Hash(\"${hash.hex}\"),")
    }
    sb.appendLine("    )")
    sb.appendLine()
    sb.appendLine("    fun resolveAbilityHash(name: String): Hash? = abilityHashes[name]")
    sb.appendLine("    fun resolveEffectHash(name: String): Hash? = effectHashes[name]")
    sb.appendLine("    fun resolveTypeHash(name: String): Hash? = typeHashes[name]")
    sb.appendLine("    fun resolveHash(name: String): Hash? = abilityHashes[name] ?: effectHashes[name] ?: typeHashes[name]")
    sb.appendLine()
    sb.appendLine("    fun isInspect(hash: Hash?): Boolean = hash != null && hash == ABILITY_INSPECT")
    sb.appendLine("    fun isMut(hash: Hash?): Boolean = hash != null && hash == EFFECT_MUT")
    sb.appendLine("    fun isCodecAbility(hash: Hash?): Boolean = hash != null && hash in codecAbilitySet")
    sb.appendLine("    /** Encode-flavored codec: codec auto-gen emits an encode-shaped impl body. */")
    sb.appendLine("    fun isEncodeFlavoredCodec(hash: Hash?): Boolean = hash != null && hash in encodeFlavoredSet")
    sb.appendLine("    /** Decode-flavored codec: codec auto-gen emits a decode-shaped impl body. */")
    sb.appendLine("    fun isDecodeFlavoredCodec(hash: Hash?): Boolean = hash != null && hash in decodeFlavoredSet")
    sb.appendLine("    fun isEq(hash: Hash?): Boolean = hash != null && hash == ABILITY_EQ")
    sb.appendLine("    fun isOrd(hash: Hash?): Boolean = hash != null && hash == ABILITY_ORD")
    sb.appendLine("    fun isNumAdd(hash: Hash?): Boolean = hash != null && hash == ABILITY_NUMADD")
    sb.appendLine("    fun isNumSub(hash: Hash?): Boolean = hash != null && hash == ABILITY_NUMSUB")
    sb.appendLine("    fun isNumMul(hash: Hash?): Boolean = hash != null && hash == ABILITY_NUMMUL")
    sb.appendLine("    fun isNumDiv(hash: Hash?): Boolean = hash != null && hash == ABILITY_NUMDIV")
    sb.appendLine("    fun isNumMod(hash: Hash?): Boolean = hash != null && hash == ABILITY_NUMMOD")
    sb.appendLine()

    // Codec abilities set
    val codecNames = listOf("Encode", "EncodeRepr", "Decode", "DecodeRepr",
        "StreamEncode", "StreamDecode", "EncodeFormat", "DecodeFormat",
        "StreamFormat", "StreamDecodeFormat", "Format")
    sb.appendLine("    private val codecAbilitySet = setOf(")
    for (name in codecNames) {
        if (abilities.containsKey(name)) {
            sb.appendLine("        ABILITY_${name.uppercase()},")
        }
    }
    sb.appendLine("    )")
    sb.appendLine()

    // Encode/decode flavor split — the codec auto-generator picks an
    // encode-shaped or decode-shaped impl body based on which family
    // the ability belongs to.
    val encodeFlavored = listOf("Encode", "EncodeRepr")
    sb.appendLine("    private val encodeFlavoredSet = setOf(")
    for (name in encodeFlavored) {
        if (abilities.containsKey(name)) {
            sb.appendLine("        ABILITY_${name.uppercase()},")
        }
    }
    sb.appendLine("    )")
    sb.appendLine()
    val decodeFlavored = listOf("Decode", "DecodeRepr")
    sb.appendLine("    private val decodeFlavoredSet = setOf(")
    for (name in decodeFlavored) {
        if (abilities.containsKey(name)) {
            sb.appendLine("        ABILITY_${name.uppercase()},")
        }
    }
    sb.appendLine("    )")

    sb.appendLine("}")

    output.writeText(sb.toString())
    println("Generated ${abilities.size} ability + ${effects.size} effect + ${types.size} type hashes → $outputPath")
}
