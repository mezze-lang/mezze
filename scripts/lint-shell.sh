#!/usr/bin/env bash
#
# Guard one bug class that this repo has now produced FIVE times:
#
#   set -o pipefail
#   producer | grep -q pattern      # grep exits on the first match…
#                                   # …SIGPIPEs producer, pipeline reports 141,
#                                   # and `if` reads that as "not found"
#
# A reader that stops early closes the pipe while the writer is still writing.
# The writer dies of SIGPIPE, `pipefail` propagates its 141, and `set -e` turns
# that into either a silent abort or — far worse — a FALSE branch: the check
# says "no match" about input that matched. Nothing in the output ever says
# "SIGPIPE".
#
# Which readers do it is not folklore; it is measured (bash 5.3, pipefail, a
# finite 2M-line producer):
#
#     | head -1            141      | tail -1         0
#     | head -n 5          141      | tail -n 5       0
#     | grep -q            141      | grep (plain)    0
#     | grep -m 1          141      | awk max         0
#     | sort -rn | head -1 141
#
# So `head`, `grep -q` and `grep -m` are flagged and `tail` is not: tail cannot
# exit early, because it has to reach EOF to know which line was last. (An
# earlier note in the memory blamed a `| tail -1` for one of these. That
# diagnosis was wrong about the mechanism.)
#
# It stays invisible until inputs grow. Instance 3 only began firing when the
# cli jar grew a 43MB entry; instance 4 hid for months because its branch needs
# a pre-existing gitignored artifact. That is why this is a lint and not a test:
# reproducing any one of them needs a specific input size, but all of them are
# visible in the source.
#
# ZSH MASKS IT. `unzip -l x | grep -q p` is 141 in bash and 0 in zsh. A
# previous session tested in zsh, got 12 clean runs, and argued itself out of
# the correct diagnosis. These scripts are bash; this runs them as bash.
#
# Fixing: capture into a variable and match that (`listing="$(unzip -l "$j")"`
# then `grep -q p <<<"$listing"`), or count instead of short-circuiting
# (`[[ $(grep -c p <<<"$x") -gt 0 ]]`), or replace `sort|head` with an awk max.
# Do NOT paper over it with `|| true` — that swallows real failures too.
#
#   bash scripts/lint-shell.sh            # lint + self-test
#   bash scripts/lint-shell.sh --self-test-only
#
set -uo pipefail   # NB: no `set -e`; this script inspects failures deliberately

cd "$(dirname "${BASH_SOURCE[0]}")/.."

red=$'\033[31m'; green=$'\033[32m'; dim=$'\033[2m'; off=$'\033[0m'
failures=0

note() { printf '%s%s%s\n' "$dim" "$1" "$off"; }
bad()  { printf '%s✗%s %s\n' "$red" "$off" "$1"; failures=$((failures + 1)); }
good() { printf '%s✓%s %s\n' "$green" "$off" "$1"; }

# A reader that stops before EOF, as a grep -E alternation applied to the text
# after a `|`. Deliberately narrow: only the three forms measured above.
# `[^|]\|[^|]` so that `||` is not read as a pipe: `cmd || ! grep -q p file`
# has no pipeline in it at all, and grep reading a FILE never SIGPIPEs anyone.
readonly EARLY_EXIT_READER='([^|]|^)\|[[:space:]]*([^|]*[[:space:]])?(head([[:space:]]|$)|grep[^|]*(-[a-zA-Z]*q|-m[[:space:]]+[0-9]))'

# Scripts this repo maintains. `.devenv/` is generated by nix (and carries the
# pattern itself, in code nobody here can fix), `website/dist/` is build output,
# and this file seeds the pattern deliberately in its own self-test fixtures.
scripts_to_check() {
  find . -name '*.sh' \
       -not -path '*/node_modules/*' \
       -not -path './.git/*' \
       -not -path './.devenv/*' \
       -not -path './.direnv/*' \
       -not -path './website/dist/*' \
       -not -path './scripts/lint-shell.sh' \
       -not -path '*/build/*' \
    | sort
}

# Pipefail scripts only. Without pipefail a SIGPIPEd writer is invisible to the
# pipeline's exit status, so the pattern is survivable there (still a smell).
pipefail_scripts() {
  local f
  while IFS= read -r f; do
    grep -qE '^[[:space:]]*set[[:space:]][^#]*pipefail' "$f" && printf '%s\n' "$f"
  done < <(scripts_to_check)
}

# Flag matches, ignoring comment lines — the fixed sites carry explanatory
# comments that quote the very pattern they warn about.
scan_file() {
  local f=$1 found=0 line
  while IFS= read -r line; do
    local text=${line#*:}
    [[ $text =~ ^[[:space:]]*# ]] && continue
    printf '    %s:%s\n' "$f" "$line"
    found=1
  done < <(grep -nE "$EARLY_EXIT_READER" "$f")
  return $((1 - found))
}

lint() {
  local f offenders=0 scanned=0
  while IFS= read -r f; do
    scanned=$((scanned + 1))
    if scan_file "$f"; then offenders=$((offenders + 1)); fi
  done < <(pipefail_scripts)

  if (( offenders > 0 )); then
    bad "$offenders of $scanned pipefail script(s) pipe into a reader that exits early"
  else
    good "$scanned pipefail scripts, no early-exiting pipeline readers"
  fi
}

# The lint's own failure mode is matching NOTHING — a broken pattern reports a
# clean tree. So prove it still bites on a seeded instance, and that it does not
# bite on the safe forms it must not flag.
self_test() {
  local tmp; tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' RETURN

  cat > "$tmp/offender.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
if unzip -l "$1" | grep -q 'stdlib-snapshot\.cbor'; then echo found; fi
newest="$(find . -printf '%T@\n' | sort -rn | head -1)"
EOF
  cat > "$tmp/clean.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
listing="$(unzip -l "$1" 2>/dev/null || true)"
grep -q 'stdlib-snapshot\.cbor' <<<"$listing" && echo found
newest="$(find . -printf '%T@\n' | awk '$1 > m { m = $1 } END { print m + 0 }')"
printf '%s\n' "$cp" | grep -E '^/' | tail -1
EOF

  local hits
  hits=$(grep -cE "$EARLY_EXIT_READER" "$tmp/offender.sh")
  if (( hits == 2 )); then
    good "self-test: the pattern catches both seeded instances"
  else
    bad "self-test: expected 2 hits in the seeded offender, got $hits — the pattern has rotted"
  fi

  hits=$(grep -cE "$EARLY_EXIT_READER" "$tmp/clean.sh")
  if (( hits == 0 )); then
    good "self-test: the pattern does not flag a here-string match, an awk max or a tail"
  else
    bad "self-test: $hits false positive(s) on the fixed forms"
  fi

  # The premise itself: if bash ever stopped SIGPIPEing these, this lint would
  # be pointless, and if `tail` started exiting early it would be incomplete.
  local rc
  seq 1 200000 | head -1 >/dev/null 2>&1; rc=$?
  if (( rc == 141 )); then
    good "self-test: bash $BASH_VERSION still reports 141 for \`| head -1\` under pipefail"
  else
    bad "self-test: \`| head -1\` gave rc=$rc, not 141 — re-measure before trusting this lint"
  fi
  seq 1 200000 | tail -1 >/dev/null 2>&1; rc=$?
  if (( rc == 0 )); then
    good "self-test: \`| tail -1\` is still safe (rc=0), so it stays unflagged"
  else
    bad "self-test: \`| tail -1\` gave rc=$rc — tail now exits early and must be flagged"
  fi
}

# Every script must also still parse. Cheap, and it catches a bad fix.
syntax() {
  local f broken=0 n=0
  while IFS= read -r f; do
    n=$((n + 1))
    bash -n "$f" 2>/dev/null || { bad "bash -n: $f does not parse"; broken=1; }
  done < <(scripts_to_check)
  (( broken == 0 )) && good "$n shell scripts parse"
}

note "shell lint — SIGPIPE under pipefail (see the header for the measurements)"
self_test
if [[ ${1-} != --self-test-only ]]; then
  syntax
  lint
fi

if (( failures > 0 )); then
  printf '\n%s%d check(s) failed%s\n' "$red" "$failures" "$off"
  exit 1
fi
printf '\n%sall checks passed%s\n' "$green" "$off"
