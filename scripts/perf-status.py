#!/usr/bin/env python3
"""Regenerate `perf/datastructures/*.md` and `perf/README.md`.

    scripts/perf-status.py

WHY THIS IS GENERATED. The per-operation checklists are 589 lines of state, and a
hand-maintained list of what has been optimised is precisely the thing that
cannot say what it is MISSING: `OP_COUNT_ALL` was declared in `NativeHofNames`
and referenced by nothing, so `iter::count` ran 88x `iter::sum` for doing less
work and no one knew. So the operation lists come from the stdlib's own
`pub let` declarations, the benched/unbenched split comes from the bench sources,
and only the NUMBERS are curated — in `perf/coverage.tsv`, one line per
measurement.

Run it after adding a bench row or a measurement. The generated files say so at
the top; edit `coverage.tsv` instead.

The area files under `perf/areas/` are PROSE and are not generated: each is a
surface whose work is not a list of operations (calls, dispatch, effects, Loom,
fusion, records, strings, startup). They carry their own status.
"""
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODS = ["seq", "list", "map", "set", "deque", "bytes", "iter",
        "sorted_map", "sorted_set", "nonemptylist", "buffer"]

# The cheapest operation each structure has, used as that structure's own floor.
# A cost is reported against this and never against a counted loop — that is how
# `asyncsurface` came to report "3 314 172/100 floor" for creating a thread.
FLOOR_OP = {
    "seq": "size", "list": "size", "map": "size", "set": "size",
    "deque": "size", "bytes": "size", "iter": "fold",
    "sorted_map": "size", "sorted_set": "size",
    "nonemptylist": "size", "buffer": "size",
}


def declared():
    out = {}
    for m in MODS:
        with open(os.path.join(ROOT, "stdlib/std/collections/%s.mz" % m),
                  encoding="utf-8") as fh:
            src = fh.read()
        out[m] = sorted(set(re.findall(r"^pub let ([a-z_][a-z0-9_]*)", src, re.M)))
    return out


def benched():
    out = defaultdict(set)
    import glob
    for path in glob.glob(os.path.join(ROOT, "bench/cases/*/src/*.mz")):
        with open(path, encoding="utf-8") as fh:
            src = fh.read()
        case = path.split("/bench/cases/")[1].split("/")[0]
        for m in MODS:
            for op in re.findall(r"\b%s::([a-z_][a-z0-9_]*)" % m, src):
                out[(m, op)].add(case)
    return out


def measured():
    out = defaultdict(list)
    path = os.path.join(ROOT, "perf/coverage.tsv")
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            f = line.split("\t")
            if len(f) < 7:
                continue
            out[(f[0], f[1])].append(
                {"ps": int(f[2]), "n": f[3], "per": f[4], "bench": f[5], "date": f[6]})
    return out


def fmt(n):
    return "{:,}".format(n).replace(",", " ")


def main():
    dec, ben, mea = declared(), benched(), measured()
    os.makedirs(os.path.join(ROOT, "perf/datastructures"), exist_ok=True)
    summary = []

    for m in MODS:
        ops = dec[m]
        floor = None
        fkey = (m, FLOOR_OP.get(m, "size"))
        if mea.get(fkey):
            floor = mea[fkey][-1]["ps"]

        lines = ["<!-- GENERATED by scripts/perf-status.py — do not edit.",
                 "     Operations come from stdlib/std/collections/%s.mz," % m,
                 "     benched/not from bench/cases/*, numbers from perf/coverage.tsv. -->",
                 "", "# %s" % m, ""]
        n_mea = sum(1 for op in ops if mea.get((m, op)))
        n_ben = sum(1 for op in ops if ben.get((m, op)))
        lines.append("%d operations · %d with a bench row · %d with a number%s"
                     % (len(ops), n_ben, n_mea,
                        (" · floor `%s::%s` = %s ps" % (m, FLOOR_OP[m], fmt(floor)))
                        if floor else ""))
        lines += ["", "| op | ps/op | elems | ps/elem | vs floor | bench |",
                  "|---|---|---|---|---|---|"]
        for op in ops:
            rec = mea.get((m, op))
            cases = ben.get((m, op))
            if rec:
                r = rec[-1]
                # PER ELEMENT, because a ratio of a whole-collection cost against
                # a point-operation floor is the `asyncsurface` mistake: it read
                # "3 314 172/100 floor" for creating a thread.
                elems = max(1, int(r["per"]))
                per_elem = r["ps"] // elems
                ratio = ("%.1fx" % (per_elem / float(floor))) if floor else "—"
                lines.append("| `%s` | %s | %s | %s | %s | %s |"
                             % (op, fmt(r["ps"]), elems if elems > 1 else "",
                                fmt(per_elem) if elems > 1 else "",
                                ratio, r["bench"]))
            elif cases:
                lines.append("| `%s` | — | | | | called in %s, no number |"
                             % (op, ", ".join(sorted(cases))))
            else:
                lines.append("| `%s` | **UNMEASURED** | | | | |" % op)
        lines += ["", "## Unmeasured (%d)" % (len(ops) - n_ben), ""]
        missing = [op for op in ops if not ben.get((m, op))]
        lines.append(", ".join("`%s`" % o for o in missing) if missing else "none")
        lines.append("")
        with open(os.path.join(ROOT, "perf/datastructures/%s.md" % m), "w",
                  encoding="utf-8") as fh:
            fh.write("\n".join(lines))
        summary.append((m, len(ops), n_ben, n_mea))

    tot = [sum(x[i] for x in summary) for i in (1, 2, 3)]
    head = ["<!-- GENERATED by scripts/perf-status.py — do not edit. -->", "",
            "# Perf status", "",
            "Where every surface stands. The data-structure pages are generated",
            "from the stdlib and the bench sources; `perf/coverage.tsv` holds the",
            "numbers and is the only file to edit by hand. The area pages under",
            "`perf/areas/` are prose and carry their own status.", "",
            "PERF-LOG.md remains the narrative: what was tried, what the cause",
            "turned out to be, and what was reverted. These pages are the index.",
            "", "## Data structures", "",
            "| module | ops | benched | numbered | cover |", "|---|---|---|---|---|"]
    for m, nd, nb, nm in sorted(summary, key=lambda r: -(r[1] - r[2])):
        head.append("| [%s](datastructures/%s.md) | %d | %d | %d | %d%% |"
                    % (m, m, nd, nb, nm, round(100.0 * nb / nd)))
    head.append("| **total** | **%d** | **%d** | **%d** | **%d%%** |"
                % (tot[0], tot[1], tot[2], round(100.0 * tot[1] / tot[0])))
    head += ["", "## Areas", "",
             "| area | status |", "|---|---|"]
    for f, desc in [
        ("function-calls", "four call spellings at parity, 617-630 ps; one open cliff"),
        ("dispatch-abilities", "an ability call costs a direct call; dictionaries were the cost"),
        ("effects", "install 2.73x this branch; `abort` is the largest number left"),
        ("continuation", "`resume` costs what its value costs; the abort unwind is open"),
        ("loom-async-parallel", "JDK-bound: Loom's floor is 5.3 us, Mezze is 1.9x it"),
        ("fusion-iter", "the pipeline surface, 1.0-10x of its floor with three exceptions"),
        ("records-variants", "unboxed at arity 1-4; variants 64 to 48 bytes"),
        ("strings", "split 1.88x, interpolation exact; case conversion is vectorisation"),
        ("startup", "820 ms jar, 78 ms native, 19 ms with -O2; 168 ms located, not landed"),
    ]:
        head.append("| [%s](areas/%s.md) | %s |" % (f, f, desc))
    head += ["", "## Regenerating", "",
             "```", "scripts/perf-status.py            # these pages",
             "scripts/collection-coverage.py    # the coverage number alone",
             "```", ""]
    with open(os.path.join(ROOT, "perf/README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(head))
    print("perf/README.md + %d data-structure pages" % len(summary))
    print("total %d ops, %d benched, %d numbered" % tuple(tot))


if __name__ == "__main__":
    main()
